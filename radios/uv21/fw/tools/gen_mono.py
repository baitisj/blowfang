"""Writes src/ui/mono_glyphs.rs: SURF's font 1 and font 2 (uv21_surf.h `text`), cut from
embedded-graphics 0.8's FONT_6X10 and FONT_10X20 (MIT/Apache-2.0, from the X11 misc-fixed fonts), so
the port draws them pixel for pixel as it did with embedded-graphics, without the crate.

    python3 radios/uv21/fw/tools/gen_mono.py ~/.cargo/registry/src/*/embedded-graphics-0.8.2

Font 1 keeps all of ASCII (720 B). Font 2 keeps only TUNE's characters (TALL_CHARS); the others
are drawn as font 1 doubled (src/ui/mono.rs)."""
# SPDX-License-Identifier: GPL-3.0-only
import os
import sys

TALL_CHARS = "0123456789.-_ "


def cells(raw, width, cw, ch):
    """each glyph of a 1-bit sheet (16 a row, from ' '), as rows of cw-bit ints, bit cw-1 = left"""
    stride = width // 8
    out = []
    for i in range(96):
        gx, gy = (i % 16) * cw, (i // 16) * ch
        rows = []
        for y in range(ch):
            v = 0
            for x in range(cw):
                b = raw[(gy + y) * stride + (gx + x) // 8] >> (7 - (gx + x) % 8) & 1
                v = v << 1 | b
            rows.append(v)
        out.append(rows)
    return out


def main():
    eg = sys.argv[1]
    raw = os.path.join(eg, "fonts", "raw", "ascii")
    small = cells(open(os.path.join(raw, "font_6x10.raw"), "rb").read(), 96, 6, 10)
    tall = cells(open(os.path.join(raw, "font_10x20.raw"), "rb").read(), 160, 10, 20)
    sel = [tall[ord(c) - 0x20] for c in TALL_CHARS]
    used = [y for y in range(20) if any(g[y] for g in sel)]
    top, bot = used[0], used[-1] + 1
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "..", "src", "ui", "mono_glyphs.rs"), "w") as f:
        f.write("// @generated by radios/uv21/fw/tools/gen_mono.py from embedded-graphics 0.8's\n"
                "// FONT_6X10 / FONT_10X20 (MIT/Apache-2.0, from the X11 misc-fixed fonts). Do not edit.\n\n")
        assert not any(r & 1 for g in small for r in g)   # (column 6 is always the gap)
        f.write("/// FONT_6X10, ' ' to DEL (0x20-0x7F): row r (0-9, top down) in bits 5r..5r+4, bit 5r+4 =\n"
                "/// the leftmost column (the sixth column, the gap, is always blank)\n")
        f.write("pub const SMALL: [u64; 96] = [\n")
        for i, g in enumerate(small):
            v = 0
            for r, bits in enumerate(g):
                v |= (bits >> 1) << (5 * r)
            f.write("    0x%013x, // %s\n" % (v, repr(chr(0x20 + i))))
        f.write("];\n\n")
        f.write("/// the characters FONT_10X20 is kept for (TUNE's digits)\n")
        f.write("pub const TALL_CHARS: &[u8] = b\"%s\";\n" % TALL_CHARS)
        f.write("/// the first of FONT_10X20's 20 rows kept; the rows above and below are blank\n")
        f.write("pub const TALL_TOP: i32 = %d;\n" % top)
        f.write("/// FONT_10X20 rows TALL_TOP.., one glyph a TALL_CHARS character: bit 9 = the leftmost column\n")
        f.write("pub const TALL: [[u16; %d]; %d] = [\n" % (bot - top, len(sel)))
        for c, g in zip(TALL_CHARS, sel):
            f.write("    [%s], // %s\n" % (", ".join("0x%03x" % r for r in g[top:bot]), repr(c)))
        f.write("];\n")
    print("rows %d..%d kept, %d tall glyphs" % (top, bot, len(sel)))


if __name__ == "__main__":
    main()
